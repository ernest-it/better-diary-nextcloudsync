/* The Android launcher icon and launch screen, from the same drawing as the desktop icon
   (build/make-icons.js): the white bookmark ribbon on the ink-blue square. Replaces the
   Capacitor placeholders. Run once after `cap add android`, or whenever the icon changes:

     node mobile/tools/make-icons.js */
'use strict';

const fs = require('node:fs');
const path = require('node:path');
const { render, encodePng } = require('../../build/make-icons.js');

const RES = path.join(__dirname, '..', 'android', 'app', 'src', 'main', 'res');
const INK = '#55638F';        // --accent
const PAPER = '#F4F1EA';      // --bg, light
const PAPER_DARK = '#1A1917'; // --bg, dark

const write = (rel, data) => {
  const file = path.join(RES, rel);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, data);
};
const remove = (rel) => fs.rmSync(path.join(RES, rel), { recursive: true, force: true });

/* Android 8+: an adaptive icon, so the launcher can mask it into its own shape. The ribbon
   keeps the proportions it has on the desktop icon, drawn inside the 72dp of the 108dp
   canvas that no mask crops. */
const at = (fraction) => (18 + 72 * fraction).toFixed(2);
write('drawable/ic_launcher_foreground.xml', `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by mobile/tools/make-icons.js — the ribbon from build/make-icons.js. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <path
        android:fillColor="#FFFFFF"
        android:pathData="M${at(0.35)},${at(0.19)} H${at(0.65)} V${at(0.81)} L54,${at(0.60)} L${at(0.35)},${at(0.81)} Z" />
</vector>
`);
for (const name of ['ic_launcher', 'ic_launcher_round']) {
  write(`mipmap-anydpi-v26/${name}.xml`, `<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background"/>
    <foreground android:drawable="@drawable/ic_launcher_foreground"/>
    <monochrome android:drawable="@drawable/ic_launcher_foreground"/>
</adaptive-icon>
`);
}
write('values/ic_launcher_background.xml', `<?xml version="1.0" encoding="utf-8"?>
<resources>
    <color name="ic_launcher_background">${INK}</color>
    <color name="splash_background">${PAPER}</color>
</resources>
`);
write('values-night/ic_launcher_background.xml', `<?xml version="1.0" encoding="utf-8"?>
<resources>
    <color name="splash_background">${PAPER_DARK}</color>
</resources>
`);
remove('drawable/ic_launcher_background.xml');
remove('drawable-v24');

/* Android 7: plain bitmaps, one per density. */
const DENSITIES = { mdpi: 48, hdpi: 72, xhdpi: 96, xxhdpi: 144, xxxhdpi: 192 };
for (const [density, size] of Object.entries(DENSITIES)) {
  const png = encodePng(size, render(size));
  write(`mipmap-${density}/ic_launcher.png`, png);
  write(`mipmap-${density}/ic_launcher_round.png`, png);
  remove(`mipmap-${density}/ic_launcher_foreground.png`);
}

/* The launch screen: the page's own background with the icon in the middle, instead of a
   Capacitor logo. Android 12+ draws its own from the theme (see styles.xml). */
for (const entry of fs.readdirSync(RES)) {
  if (/^drawable-(land|port)-/.test(entry)) remove(entry);
}
remove('drawable/splash.png');
write('drawable/splash.xml', `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by mobile/tools/make-icons.js -->
<layer-list xmlns:android="http://schemas.android.com/apk/res/android">
    <item android:drawable="@color/splash_background" />
    <item android:width="96dp" android:height="96dp" android:gravity="center">
        <bitmap android:src="@mipmap/ic_launcher" android:gravity="fill" />
    </item>
</layer-list>
`);

console.log('icons: launcher icon and launch screen written to', path.relative(process.cwd(), RES));
